"""Русский текст в консоли на Windows.

Консоль на Windows по умолчанию cp1252, а kurator говорит по-русски.
Печать падает с `UnicodeEncodeError` — и уносит приложение целиком,
потому что приходит из `print`, а не из логики: пользователь видит
краш вместо работы.

В консольном варианте сборки это стоило шести прогонов CI: приложение
падало на первой же строке вывода, с кодом -1 и сообщением
`LoadLibrary`, которое на самом деле было лишь первым симптомом.

Оконная сборка молчала: у неё `sys.stdout` равен `None`, и `print` не
делает ничего. То есть на живой машине поломка выглядела бы иначе —
как пустое окно, — и diagnosed бы только при сборке проверочного
варианта. Именно ради этого он и собирается.

Функция не меняет логику. Она говорит потокам, что кириллица — это
utf-8, а не cp1252, и что непечатный символ лучше заменить, чем уронить
программу. Перенастраивать имеет смысл только то, что уже есть:
в оконном приложении потоков нет, и это нормальный случай.
"""

from __future__ import annotations

import sys
from typing import IO


def utf8_stdio(streams: tuple[IO[str], ...] | None = None) -> None:
    """Научить потоки печатать по-русски.

    `errors="replace"` — не украшение: без него один символ вне
    кодировки обрывает программу, а с ним сообщение выводится целиком.
    """
    for stream in streams if streams is not None else (sys.stdout, sys.stderr):
        if stream is None:
            continue
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError, OSError):
            # Окно без консоли, подменённый поток, поток не текстовый —
            # во всех трёх случаях перенастраивать нечего.
            pass
